#!/usr/bin/env node
// Put the generator's catalog.json where the app and the settings page use it:
//   watchface/src/pkjs/catalog-data.js  bundled into the .pbw (PebbleKit JS)
//   server/static/config/catalog.json   loaded by the settings page
// Both are generated, not committed. Run after the generator's --bundle step:
//   node scripts/bundle-catalog.mjs [catalog/catalog.json]
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2] || 'catalog/catalog.json';
const json = readFileSync(source, 'utf8');
const data = JSON.parse(json);
writeFileSync('watchface/src/pkjs/catalog-data.js',
  `// Generated by scripts/bundle-catalog.mjs from ${source}; do not edit.\nmodule.exports = ${json};\n`);
writeFileSync('server/static/config/catalog.json', json);
console.log(`catalog v${data.version}: ${data.paintings.length} paintings, ${data.featured.length} featured, ${(json.length / 1e6).toFixed(2)} MB`);
